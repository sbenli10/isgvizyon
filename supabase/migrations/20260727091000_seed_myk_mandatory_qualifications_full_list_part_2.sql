insert into public.myk_mandatory_qualifications (
  profession_name,
  normalized_profession_name,
  qualification_codes,
  obligation_date,
  source_hash,
  is_active,
  last_seen_at
)
select
  profession_name,
  lower(profession_name),
  qualification_codes,
  obligation_date,
  md5(profession_name || '|' || array_to_string(qualification_codes, ',') || '|' || obligation_date),
  true,
  now()
from data
on conflict (normalized_profession_name)
do update set
  profession_name = excluded.profession_name,
  qualification_codes = excluded.qualification_codes,
  obligation_date = excluded.obligation_date,
  source_hash = excluded.source_hash,
  is_active = true,
  last_seen_at = now();
